// tools/gen-chart-gallery.mjs — regenerate site/chart-gallery.js from the REAL chart
// registry (LF30: marketing chart-type gallery). The public site (index.html) shows a
// tile grid of every chart type Studio supports; those must never go stale as chart
// types are added, so this script boots the actual app in headless Chromium (mirrors
// gen-shots.mjs's boot) and reads Studio.chartCatalog() straight from the source of
// truth (app/model.js's Studio.CHARTS + app/chart-thumbnails.js's Studio.CHART_SVG).
//
// Run whenever chart types change, and commit the result:
//
//   node tools/gen-chart-gallery.mjs
import http from "node:http";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { execSync } from "node:child_process";

// Playwright lives in the GLOBAL npm root here (same install the test suite uses);
// ESM ignores NODE_PATH, so resolve it explicitly.
const require = createRequire(path.join(execSync("npm root -g").toString().trim(), "x.js"));
const { chromium } = require("playwright");

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "site", "chart-gallery.js");
const PORT = 4311;
const MIME = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css",
  ".json": "application/json", ".svg": "image/svg+xml", ".png": "image/png", ".webmanifest": "application/json" };

function serve() {
  return new Promise((res) => {
    const srv = http.createServer((req, rep) => {
      let p = decodeURIComponent(req.url.split("?")[0]);
      if (p === "/") p = "/index.html";
      let fp = path.join(ROOT, p);
      if (fs.existsSync(fp) && fs.statSync(fp).isDirectory()) fp = path.join(fp, "index.html");
      if (!fp.startsWith(ROOT) || !fs.existsSync(fp) || fs.statSync(fp).isDirectory()) { rep.writeHead(404); return rep.end("404"); }
      rep.writeHead(200, { "Content-Type": MIME[path.extname(fp)] || "application/octet-stream" });
      fs.createReadStream(fp).pipe(rep);
    });
    srv.listen(PORT, () => res(srv));
  });
}

(async () => {
  const srv = await serve();
  const exePath = process.env.PW_CHROMIUM_PATH || "/opt/pw-browsers/chromium-1194/chrome-linux/chrome";
  const launchOpts = { headless: true };
  if (fs.existsSync(exePath)) launchOpts.executablePath = exePath;
  const browser = await chromium.launch(launchOpts);

  try {
    const ctx = await browser.newContext();
    const page = await ctx.newPage();
    await page.addInitScript(() => {
      try { sessionStorage.setItem("studio-gate-ok", "1"); localStorage.setItem("studio-welcome-seen", "1"); } catch (e) {}
    });
    await page.goto(`http://localhost:${PORT}/app/`, { waitUntil: "networkidle" });
    await page.waitForFunction(() => window.__studioChartCatalog, { timeout: 15000 });
    const catalog = await page.evaluate(() => window.__studioChartCatalog());
    await ctx.close();

    if (!Array.isArray(catalog) || catalog.length < 30) {
      throw new Error(`catalog too small (${catalog && catalog.length}) — expected 30+ chart types`);
    }
    const body = "// AUTO-GENERATED by tools/gen-chart-gallery.mjs — do not hand-edit.\n"
      + "// Regenerate with: node tools/gen-chart-gallery.mjs\n"
      + "window.CHART_GALLERY = " + JSON.stringify(catalog, null, 2) + ";\n";
    fs.writeFileSync(OUT, body);
    console.log(`gen-chart-gallery: wrote ${catalog.length} chart types → site/chart-gallery.js`);
  } finally {
    await browser.close();
    srv.close();
  }
})();
